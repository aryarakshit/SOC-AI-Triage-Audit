def _decode(b64_str: str) -> str:
    """Decode base64 encoded string to prevent AV false-positive detection of test signatures."""
    return base64.b64decode(b64_str.encode("ascii")).decode("utf-8")

def get_default_cases() -> List[Dict[str, Any]]:
    """Return the canonical list of 100 realistic HomeSOC alerts across 6 threat categories."""
    cases: List[Dict[str, Any]] = []
    for c in _ENCODED_CASES:
        cmd = _decode(c["b64_cmd"])
        cases.append({
            "case_id": c["case_id"],
            "category": c["category"],
            "rule_id": c["rule_id"],
            "rule_level": c["rule_level"],
            "host": c["host"],
            "raw_telemetry": {
                "commandLine": cmd,
                "parentImage": c["parentImage"],
                "image": c["image"],
                "user": c["user"],
                "srcip": c["srcip"]
            },
            "analyst_verdict": c["analyst_verdict"],
            "analyst_mitre_id": c["analyst_mitre_id"],
            "analyst_notes": c["analyst_notes"],
            "challenge_type": c["challenge_type"]
        })
    return cases

def init_database(db_path: Path = DEFAULT_DB_PATH) -> None:
    """Create SQLite schema for ground truth cases and AI triage results."""
    db_path.parent.mkdir(parents=True, exist_ok=True)
    conn = sqlite3.connect(str(db_path))
    cursor = conn.cursor()

    cursor.execute("""
        CREATE TABLE IF NOT EXISTS ground_truth_cases (
            case_id INTEGER PRIMARY KEY,
            category TEXT NOT NULL,
            rule_id TEXT NOT NULL,
            rule_level INTEGER NOT NULL,
            host TEXT NOT NULL,
            raw_telemetry_json TEXT NOT NULL,
            analyst_verdict TEXT NOT NULL,
            analyst_mitre_id TEXT NOT NULL,
            analyst_notes TEXT NOT NULL,
            challenge_type TEXT NOT NULL
        )
    """)

    cursor.execute("""
        CREATE TABLE IF NOT EXISTS ai_triage_results (
            case_id INTEGER PRIMARY KEY,
            ai_verdict TEXT,
            ai_confidence REAL,
            ai_mitre_id TEXT,
            ai_ticket_note TEXT,
            inference_latency_ms REAL,
            is_correct INTEGER,
            failure_mode TEXT,
            hitl_signoff_required INTEGER,
            FOREIGN KEY (case_id) REFERENCES ground_truth_cases(case_id)
        )
    """)

    conn.commit()
    conn.close()

def seed_database(db_path: Path = DEFAULT_DB_PATH, overwrite: bool = True) -> int:
    """Seed the database with 100 analyst-verified alerts."""
    init_database(db_path)
    cases = get_default_cases()

    conn = sqlite3.connect(str(db_path))
    cursor = conn.cursor()

    if overwrite:
        cursor.execute("DELETE FROM ground_truth_cases")
        cursor.execute("DELETE FROM ai_triage_results")

    for c in cases:
        cursor.execute("""
            INSERT OR REPLACE INTO ground_truth_cases (
                case_id, category, rule_id, rule_level, host,
                raw_telemetry_json, analyst_verdict, analyst_mitre_id,
                analyst_notes, challenge_type
            ) VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?)
        """, (
            c["case_id"],
            c["category"],
            c["rule_id"],
            c["rule_level"],
            c["host"],
            json.dumps(c["raw_telemetry"], indent=2),
            c["analyst_verdict"],
            c["analyst_mitre_id"],
            c["analyst_notes"],
            c["challenge_type"]
        ))

    conn.commit()
    count = cursor.execute("SELECT COUNT(*) FROM ground_truth_cases").fetchone()[0]
    conn.close()
    return count

if __name__ == "__main__":
    count = seed_database()
    print(f"Successfully seeded {count} HomeSOC ground-truth alerts in {DEFAULT_DB_PATH}")
